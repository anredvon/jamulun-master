def _deck_card(card_id, title, english, keyword, arcana, flow, caution, line, suit=None, rank=None):
    card = {
        "id": card_id,
        "title": title,
        "en": english,
        "status": keyword,
        "arcana": arcana,
        "flow": flow,
        "caution": caution,
        "line": line,
        "image": f"images/tarot/moneyflow_78/{card_id}.jpg",
    }
    if suit:
        card["suit"] = suit
    if rank:
        card["rank"] = rank
    return card


